#!/usr/bin/env node
/**
 * hivemind-launcher.mjs
 *
 * Launches HiveMind Protocol v2 with credentials sourced from bootstrap env.
 * Never hardcodes tokens. Two approaches, both run — server is primary:
 *
 *   Approach A (fallback):  writes hivemind-config.js alongside the HTML
 *                           so opening the file directly still works
 *   Approach B (primary):   HTTP server on HM_PORT (default 7474) injects
 *                           tokens as inline <script> at serve-time;
 *                           also proxies /api/anthropic to avoid CORS
 *
 * Token resolution order (each var):
 *   1. Explicit env var (HM_GH_TOKEN, HM_CLAUDE_TOKEN)
 *   2. Bootstrap aliases (BCLARK00_TOKEN, ANTHROPIC_API_KEY)
 *   3. bootstrap() return value (credentials.bclark00)
 *   4. Prompt stdin (interactive fallback, only if TTY)
 *
 * Usage:
 *   node hivemind-launcher.mjs                    # standalone
 *   node hivemind-launcher.mjs --no-server        # config file only
 *   node hivemind-launcher.mjs --no-config        # server only
 *   node hivemind-launcher.mjs --open             # also open browser
 *
 * Or from bootstrap:
 *   import { launchHiveMind } from './hivemind-launcher.mjs';
 *   await launchHiveMind({ credentials, flags: ['--open'] });
 */

import { createServer }    from 'http';
import { promises as fs }  from 'fs';
import { createInterface } from 'readline';
import { fileURLToPath }   from 'url';
import { dirname, join, resolve } from 'path';
import { exec }            from 'child_process';

const __dir   = dirname(fileURLToPath(import.meta.url));
const HTML_RELATIVE = process.env.HM_HTML || '../outputs/hivemind-v2.html';
const HTML_PATH = resolve(__dir, HTML_RELATIVE);

const DEFAULT_PORT = parseInt(process.env.HM_PORT || '7474');

// ── CLI flags ──────────────────────────────────────────────────────────────
const args     = process.argv.slice(2);
const noServer = args.includes('--no-server');
const noConfig = args.includes('--no-config');
const doOpen   = args.includes('--open');

// ── Token resolution ───────────────────────────────────────────────────────
async function resolveToken(envKey, aliases = [], bootstrapVal = '', label = envKey) {
  // 1. Explicit env
  let t = process.env[envKey] || '';
  if (t) return t;

  // 2. Aliased env vars
  for (const alias of aliases) {
    t = process.env[alias] || '';
    if (t) return t;
  }

  // 3. Bootstrap-passed value
  if (bootstrapVal) return bootstrapVal;

  // 4. stdin prompt (TTY only)
  if (process.stdin.isTTY) {
    const rl = createInterface({ input: process.stdin, output: process.stderr });
    t = await new Promise(res => rl.question(`  ${label}: `, ans => { rl.close(); res(ans.trim()); }));
    if (t) return t;
  }

  return '';
}

// ── Approach A: write hivemind-config.js ──────────────────────────────────
async function writeConfigFile(tokens, htmlDir) {
  const configPath = join(htmlDir, 'hivemind-config.js');
  const content = [
    '// hivemind-config.js — generated by hivemind-launcher, never commit this file',
    `// Generated: ${new Date().toISOString()}`,
    `window.HM_GH_TOKEN     = ${JSON.stringify(tokens.gh)};`,
    `window.HM_CLAUDE_TOKEN = ${JSON.stringify(tokens.claude)};`,
  ].join('\n') + '\n';

  await fs.writeFile(configPath, content, 'utf8');

  // Patch the HTML to load the config script if not already present
  let html = await fs.readFile(HTML_PATH, 'utf8');
  const configTag = '<script src="hivemind-config.js"></script>';
  if (!html.includes('hivemind-config.js')) {
    html = html.replace('<script>', `${configTag}\n<script>`);
    await fs.writeFile(HTML_PATH, html, 'utf8');
    console.log('  [config] Patched HTML to load hivemind-config.js');
  }

  console.log(`  [config] Written: ${configPath}`);
  return configPath;
}

// ── Anthropic proxy handler ────────────────────────────────────────────────
function proxyAnthropic(req, res, claudeToken) {
  // Strip our proxy prefix, forward to real API
  const target = 'https://api.anthropic.com';
  const upstreamPath = req.url.replace(/^\/proxy\/anthropic/, '');

  let body = '';
  req.on('data', chunk => body += chunk);
  req.on('end', () => {
    const { hostname, pathname, search } = new URL(target + upstreamPath);
    const options = {
      hostname,
      path: pathname + (search || ''),
      method: req.method,
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': claudeToken,
        'anthropic-version': '2023-06-01',
        // Do NOT forward the dangerous-direct-browser-access header
      },
    };

    import('https').then(({ default: https, request }) => {
      const upstream = (request || https.request)(options, upRes => {
        res.writeHead(upRes.statusCode, {
          'Content-Type': upRes.headers['content-type'] || 'application/json',
          'Access-Control-Allow-Origin': '*',
        });
        upRes.pipe(res);
      });
      upstream.on('error', err => {
        res.writeHead(502); res.end(JSON.stringify({ error: err.message }));
      });
      if (body) upstream.write(body);
      upstream.end();
    });
  });
}

// ── Approach B: HTTP server ────────────────────────────────────────────────
async function startServer(tokens, port) {
  const html = await fs.readFile(HTML_PATH, 'utf8');

  // Inject tokens as first <script> block, and rewrite the Claude API URL
  // to use our local proxy instead of direct browser calls
  const injection = [
    '<script>',
    `// Injected by hivemind-launcher at ${new Date().toISOString()}`,
    `window.HM_GH_TOKEN     = ${JSON.stringify(tokens.gh)};`,
    `window.HM_CLAUDE_TOKEN = ${JSON.stringify(tokens.claude)};`,
    // Override the API URL so transmit() hits our proxy
    `window.HM_CLAUDE_API_OVERRIDE = 'http://localhost:${port}/proxy/anthropic/v1/messages';`,
    '</script>',
  ].join('\n');

  // Patch CLAUDE_API in the served HTML to use the proxy URL
  const servedHtml = html
    .replace('<head>', `<head>\n${injection}`)
    .replace(
      /const CLAUDE_API\s*=\s*['"]https:\/\/api\.anthropic\.com\/v1\/messages['"]/,
      `const CLAUDE_API = window.HM_CLAUDE_API_OVERRIDE || 'https://api.anthropic.com/v1/messages'`
    );

  return new Promise((resolve, reject) => {
    const server = createServer((req, res) => {
      // CORS preflight
      if (req.method === 'OPTIONS') {
        res.writeHead(204, { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': '*' });
        res.end();
        return;
      }

      // Anthropic proxy
      if (req.url.startsWith('/proxy/anthropic')) {
        proxyAnthropic(req, res, tokens.claude);
        return;
      }

      // Serve HTML
      if (req.url === '/' || req.url === '/index.html') {
        res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
        res.end(servedHtml);
        return;
      }

      res.writeHead(404); res.end('Not found');
    });

    server.listen(port, '127.0.0.1', () => resolve(server));
    server.on('error', err => {
      if (err.code === 'EADDRINUSE') reject(new Error(`Port ${port} in use`));
      else reject(err);
    });
  });
}

// ── Browser open ───────────────────────────────────────────────────────────
function openBrowser(url) {
  const cmd = process.platform === 'win32'  ? `start "" "${url}"` :
              process.platform === 'darwin' ? `open "${url}"` :
                                              `xdg-open "${url}"`;
  exec(cmd, err => { if (err) console.warn(`  [open] Could not open browser: ${err.message}`); });
}

// ── Main ───────────────────────────────────────────────────────────────────
export async function launchHiveMind({ credentials = {}, flags = [] } = {}) {
  // Merge CLI flags with caller flags
  const allFlags = [...flags, ...args];
  const effectiveNoServer = allFlags.includes('--no-server') || noServer;
  const effectiveNoConfig = allFlags.includes('--no-config') || noConfig;
  const effectiveOpen     = allFlags.includes('--open')      || doOpen;

  console.log('\n[HiveMind] Resolving tokens...');

  const ghToken = await resolveToken(
    'HM_GH_TOKEN',
    ['BCLARK00_TOKEN'],
    credentials.bclark00 || '',
    'GitHub PAT (bclark00)'
  );

  const claudeToken = await resolveToken(
    'HM_CLAUDE_TOKEN',
    ['ANTHROPIC_API_KEY', 'CLAUDE_API_KEY'],
    credentials.anthropic || '',
    'Anthropic API key'
  );

  const tokens = { gh: ghToken, claude: claudeToken };

  // Validate HTML file exists
  try { await fs.access(HTML_PATH); }
  catch { throw new Error(`hivemind-v2.html not found at: ${HTML_PATH}\nSet HM_HTML env var to override.`); }

  const htmlDir = dirname(HTML_PATH);
  const results = { configPath: null, serverUrl: null, server: null };

  // Approach A: config file (unless --no-config)
  if (!effectiveNoConfig) {
    try {
      console.log('[HiveMind] Approach A: writing hivemind-config.js...');
      results.configPath = await writeConfigFile(tokens, htmlDir);
      console.log(`  [config] OK — open file directly: file://${HTML_PATH}`);
    } catch (err) {
      console.warn(`  [config] FAILED: ${err.message}`);
    }
  }

  // Approach B: HTTP server (unless --no-server)
  if (!effectiveNoServer) {
    let port = DEFAULT_PORT;
    let attempts = 0;
    while (attempts < 5) {
      try {
        console.log(`[HiveMind] Approach B: starting server on port ${port}...`);
        results.server = await startServer(tokens, port);
        results.serverUrl = `http://localhost:${port}`;
        console.log(`  [server] OK — ${results.serverUrl}`);
        console.log(`  [server] Anthropic proxy: ${results.serverUrl}/proxy/anthropic/v1/messages`);
        break;
      } catch (err) {
        if (err.message.includes('in use')) {
          console.warn(`  [server] Port ${port} in use, trying ${port + 1}...`);
          port++;
          attempts++;
        } else {
          console.warn(`  [server] FAILED: ${err.message}`);
          if (results.configPath) {
            console.log(`  [server] Falling back to config file: file://${HTML_PATH}`);
          } else {
            throw err; // both failed
          }
          break;
        }
      }
    }
  }

  // Summary
  console.log('\n[HiveMind] Launch summary:');
  if (results.serverUrl) {
    console.log(`  Primary   (server):  ${results.serverUrl}`);
    console.log(`    Tokens injected at serve-time, proxy handles CORS`);
  }
  if (results.configPath) {
    console.log(`  Fallback  (config):  file://${HTML_PATH}`);
    console.log(`    Tokens written to: ${results.configPath}`);
  }
  if (!results.serverUrl && !results.configPath) {
    throw new Error('[HiveMind] Both launch approaches failed');
  }

  // Open browser
  if (effectiveOpen) {
    const url = results.serverUrl || `file://${HTML_PATH}`;
    console.log(`\n[HiveMind] Opening browser: ${url}`);
    openBrowser(url);
  }

  // Graceful shutdown on SIGINT
  if (results.server) {
    process.once('SIGINT', () => {
      console.log('\n[HiveMind] Shutting down server...');
      results.server.close(() => process.exit(0));
    });
    console.log('\n[HiveMind] Server running. Ctrl+C to stop.\n');
    // Keep process alive
    await new Promise(() => {});
  }

  return results;
}

// ── Standalone entry point ─────────────────────────────────────────────────
if (import.meta.url === `file://${process.argv[1]}`) {
  launchHiveMind().catch(err => {
    console.error(`[HiveMind] Fatal: ${err.message}`);
    process.exit(1);
  });
}
